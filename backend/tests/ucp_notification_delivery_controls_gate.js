'use strict';
const assert=require('node:assert/strict');
const {validatePreferences,normalizePreferences,deliveryPlan}=require('../src/services/notificationDeliveryPolicy');
const preference={locale:'ur',optional_email:false,optional_sms:false,muted_info:true,quiet_start:'22:00',quiet_end:'08:00',timezone_offset_minutes:300};
assert.equal(validatePreferences(preference).locale,'ur');
assert.throws(()=>validatePreferences({...preference,quiet_end:null}),/Invalid/);
assert.throws(()=>validatePreferences({...preference,quiet_start:'25:00'}),/Invalid/);
assert.throws(()=>validatePreferences({...preference,user_id:99}),/Invalid/);
assert.equal(normalizePreferences({quiet_start:'22:00:00'}).quiet_start,'22:00');
const now=new Date('2026-11-16T18:00:00Z');
const urgent=deliveryPlan({preference,projection:{mandatory:true,email:true,routine:true},now});
assert.equal(urgent.sendEmail,true);assert.equal(urgent.muted,false);assert.equal(urgent.notBefore,null);
const routine=deliveryPlan({preference,projection:{mandatory:false,email:true,routine:true},now});
assert.equal(routine.muted,true);assert.equal(routine.sendEmail,false);
const normal=deliveryPlan({preference:{...preference,muted_info:false,optional_email:true},projection:{email:true},now});
assert.equal(normal.notBefore.toISOString(),'2026-11-17T03:00:00.000Z');
const boundary=deliveryPlan({preference,projection:{email:true},now:new Date('2026-11-17T03:00:00Z')});
assert.equal(boundary.notBefore,null);
assert.equal(deliveryPlan({preference:{optional_email:true},projection:{routine:true},digestEnabled:true,now}).digest,true);
console.log('PASS: notification preference ownership fields, quiet boundaries, digest selection, mandatory override');
