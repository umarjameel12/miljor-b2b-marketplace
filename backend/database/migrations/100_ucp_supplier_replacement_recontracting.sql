CREATE TABLE IF NOT EXISTS supplier_replacement_quotes (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  quote_code VARCHAR(32) NOT NULL,
  original_order_id INT NOT NULL,
  original_supplier_id INT NOT NULL,
  replacement_supplier_id INT NOT NULL,
  buyer_id INT NOT NULL,
  pool_id INT NULL,
  replacement_listing_id INT NULL,
  quote_version INT UNSIGNED NOT NULL,
  sku_match_type ENUM('EXACT_SKU', 'EQUIVALENT_SKU_REQUIRES_CONSENT') NOT NULL DEFAULT 'EXACT_SKU',
  original_sku_snapshot_json JSON NOT NULL,
  replacement_sku_snapshot_json JSON NOT NULL,
  quantity DECIMAL(12,4) NOT NULL,
  old_unit_price_pkr DECIMAL(12,2) NOT NULL,
  new_unit_price_pkr DECIMAL(12,2) NOT NULL,
  old_delivery_fee_pkr DECIMAL(12,2) NOT NULL,
  new_delivery_fee_pkr DECIMAL(12,2) NOT NULL,
  old_total_pkr DECIMAL(12,2) NOT NULL,
  new_total_pkr DECIMAL(12,2) NOT NULL,
  charge_diff_pkr DECIMAL(12,2) NOT NULL,
  cost_responsibility ENUM('SUPPLIER_CARRIER_FAILURE', 'BUYER_REQUESTED', 'PLATFORM_PROVIDER_FAULT', 'DISPUTED_RESPONSIBILITY') NOT NULL,
  delivery_terms_json JSON NOT NULL,
  proposed_eta_at DATETIME NOT NULL,
  expires_at DATETIME NOT NULL,
  quote_hash CHAR(64) NOT NULL,
  status ENUM(
    'PENDING_BUYER_CONSENT',
    'BUYER_ACCEPTED',
    'BUYER_DECLINED',
    'EXPIRED',
    'EXECUTED',
    'BLOCKED_PAYMENT_REQUIRED',
    'SUPERSEDED',
    'FAILED'
  ) NOT NULL DEFAULT 'PENDING_BUYER_CONSENT',
  replacement_order_id INT NULL,
  initiated_by INT NOT NULL,
  initiated_role ENUM('ADMIN', 'SUPER_ADMIN', 'SUPPLIER', 'SYSTEM') NOT NULL,
  reason TEXT NOT NULL,
  decided_by INT NULL,
  decided_at DATETIME NULL,
  executed_at DATETIME NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  decision_idempotency_key VARCHAR(120) NULL,
  execution_idempotency_key VARCHAR(120) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_repl_orig_order FOREIGN KEY (original_order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_orig_sup FOREIGN KEY (original_supplier_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_new_sup FOREIGN KEY (replacement_supplier_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_buyer FOREIGN KEY (buyer_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_new_order FOREIGN KEY (replacement_order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_initiator FOREIGN KEY (initiated_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_decider FOREIGN KEY (decided_by) REFERENCES users(id) ON DELETE SET NULL,
  UNIQUE KEY uq_repl_quote_code (quote_code),
  UNIQUE KEY uq_repl_quote_order_ver (original_order_id, quote_version),
  UNIQUE KEY uq_repl_quote_idem (original_order_id, idempotency_key),
  KEY idx_repl_quote_buyer (buyer_id, status, expires_at),
  KEY idx_repl_quote_supplier (replacement_supplier_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS order_replacement_links (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  original_order_id INT NOT NULL,
  replacement_order_id INT NOT NULL,
  replacement_quote_id BIGINT NOT NULL,
  link_status ENUM('CREATED_AWAITING_PAYMENT', 'FUNDED_ACTIVE', 'CANCELLED') NOT NULL DEFAULT 'CREATED_AWAITING_PAYMENT',
  evidence_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_repl_link_orig FOREIGN KEY (original_order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_link_new FOREIGN KEY (replacement_order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repl_link_quote FOREIGN KEY (replacement_quote_id) REFERENCES supplier_replacement_quotes(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_repl_link_quote (replacement_quote_id),
  UNIQUE KEY uq_repl_link_orders (original_order_id, replacement_order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
