-- 099 Phase C: Shared UCP Delivery Runs, Stops, Attempts, and Versioned Amendments
-- Preserves 047 procurement_delivery_runs, 055 flash_order_delivery_terms, and 096-098 UCP tables untouched.
-- Forward-only schema for Regular & Flash delivery clustering, SQL cutoffs, pickup claims,
-- partial receipt evidence, failed delivery attempts, and buyer-consented cost/reroute amendments.

CREATE TABLE IF NOT EXISTS delivery_runs (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  run_code VARCHAR(32) NOT NULL,
  supplier_id INT NOT NULL,
  cluster_id INT NOT NULL,
  mode ENUM('STANDARD_CLUSTERED', 'EXPRESS', 'PICKUP') NOT NULL,
  handling_class VARCHAR(32) NOT NULL DEFAULT 'AMBIENT',
  delivery_day DATE NOT NULL,
  delivery_window VARCHAR(60) NOT NULL,
  cutoff_at DATETIME NOT NULL,
  max_stops SMALLINT UNSIGNED NOT NULL DEFAULT 25,
  planned_stops SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('FORMING', 'CUTOFF_LOCKED', 'DISPATCHED', 'COMPLETED', 'PARTIAL', 'FAILED', 'CANCELLED') NOT NULL DEFAULT 'FORMING',
  eta_at DATETIME NULL,
  eta_version INT UNSIGNED NOT NULL DEFAULT 0,
  eta_reason VARCHAR(255) NULL,
  cutoff_locked_at DATETIME NULL,
  dispatched_at DATETIME NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  idempotency_key VARCHAR(120) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  snapshot_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_delivery_run_supplier FOREIGN KEY (supplier_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_run_cluster FOREIGN KEY (cluster_id) REFERENCES geographic_clusters(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_delivery_run_code (run_code),
  UNIQUE KEY uq_delivery_run_idem (supplier_id, idempotency_key),
  KEY idx_delivery_run_match (supplier_id, cluster_id, mode, handling_class, delivery_day, delivery_window, status),
  KEY idx_delivery_run_cutoff (status, cutoff_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS delivery_run_stops (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  run_id BIGINT NOT NULL,
  order_id INT NOT NULL,
  buyer_id INT NOT NULL,
  supplier_id INT NOT NULL,
  cluster_id INT NOT NULL,
  mode ENUM('STANDARD_CLUSTERED', 'EXPRESS', 'PICKUP') NOT NULL,
  address_id BIGINT NULL,
  pickup_point_id INT NULL,
  stop_sequence SMALLINT UNSIGNED NOT NULL,
  active_order_key INT GENERATED ALWAYS AS (
    IF(status IN ('ASSIGNED', 'DISPATCHED', 'REATTEMPT_SCHEDULED', 'SUPPLIER_DELIVERED', 'REROUTED'), order_id, NULL)
  ) STORED,
  status ENUM(
    'ASSIGNED',
    'DISPATCHED',
    'SUPPLIER_DELIVERED',
    'BUYER_CONFIRMED',
    'PARTIAL_CONFIRMED',
    'FAILED',
    'REATTEMPT_SCHEDULED',
    'REROUTED',
    'CANCELLED'
  ) NOT NULL DEFAULT 'ASSIGNED',
  locked_delivery_fee_pkr DECIMAL(12,2) NOT NULL,
  ordered_qty DECIMAL(12,4) NOT NULL,
  accepted_qty DECIMAL(12,4) NULL,
  missing_qty DECIMAL(12,4) NULL,
  rejected_qty DECIMAL(12,4) NULL,
  disputed_qty DECIMAL(12,4) NULL,
  eta_at DATETIME NULL,
  eta_version INT UNSIGNED NOT NULL DEFAULT 0,
  attempt_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  max_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 3,
  pickup_code_hash CHAR(64) NULL,
  pickup_code_encrypted TEXT NULL,
  pickup_code_issued_at DATETIME NULL,
  pickup_claimed_at DATETIME NULL,
  supplier_delivered_at DATETIME NULL,
  buyer_confirmed_at DATETIME NULL,
  dispute_id INT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  snapshot_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_delivery_stop_run FOREIGN KEY (run_id) REFERENCES delivery_runs(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_buyer FOREIGN KEY (buyer_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_supplier FOREIGN KEY (supplier_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_cluster FOREIGN KEY (cluster_id) REFERENCES geographic_clusters(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_address FOREIGN KEY (address_id) REFERENCES buyer_delivery_addresses(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_pickup FOREIGN KEY (pickup_point_id) REFERENCES supplier_pickup_points(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_stop_dispute FOREIGN KEY (dispute_id) REFERENCES order_disputes(id) ON DELETE SET NULL,
  CONSTRAINT chk_delivery_stop_fee CHECK (locked_delivery_fee_pkr >= 0),
  UNIQUE KEY uq_delivery_stop_active_order (active_order_key),
  UNIQUE KEY uq_delivery_stop_run_seq (run_id, stop_sequence),
  KEY idx_delivery_stop_buyer (buyer_id, status),
  KEY idx_delivery_stop_supplier (supplier_id, status),
  KEY idx_delivery_stop_order (order_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS delivery_attempts (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  stop_id BIGINT NOT NULL,
  run_id BIGINT NOT NULL,
  order_id INT NOT NULL,
  attempt_number SMALLINT UNSIGNED NOT NULL,
  outcome ENUM('FAILED', 'SUCCEEDED', 'PARTIAL') NOT NULL,
  reason_code VARCHAR(64) NOT NULL,
  notes TEXT NULL,
  evidence_json JSON NULL,
  actor_id INT NOT NULL,
  actor_role ENUM('SUPPLIER', 'BUYER', 'ADMIN', 'SUPER_ADMIN', 'SYSTEM') NOT NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_delivery_attempt_stop FOREIGN KEY (stop_id) REFERENCES delivery_run_stops(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_attempt_run FOREIGN KEY (run_id) REFERENCES delivery_runs(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_attempt_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_attempt_actor FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_delivery_attempt_idem (stop_id, idempotency_key),
  UNIQUE KEY uq_delivery_attempt_num (stop_id, attempt_number),
  KEY idx_delivery_attempt_order (order_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS delivery_amendments (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  amendment_code VARCHAR(32) NOT NULL,
  order_id INT NOT NULL,
  stop_id BIGINT NULL,
  buyer_id INT NOT NULL,
  supplier_id INT NOT NULL,
  amendment_type ENUM('REATTEMPT', 'REROUTE', 'ADDRESS_CHANGE', 'MODE_CHANGE', 'WINDOW_CHANGE', 'ADMIN_RECOVERY') NOT NULL,
  amendment_version INT UNSIGNED NOT NULL,
  cost_responsibility ENUM(
    'BUYER_REQUESTED',
    'SUPPLIER_CARRIER_FAILURE',
    'PLATFORM_PROVIDER_FAULT',
    'DISPUTED_RESPONSIBILITY',
    'NO_EXTRA_COST'
  ) NOT NULL,
  initiating_actor_id INT NOT NULL,
  initiating_actor_role ENUM('BUYER', 'SUPPLIER', 'ADMIN', 'SUPER_ADMIN', 'SYSTEM') NOT NULL,
  reason TEXT NOT NULL,
  sku_snapshot_json JSON NOT NULL,
  old_amount_pkr DECIMAL(12,2) NOT NULL,
  new_amount_pkr DECIMAL(12,2) NOT NULL,
  charge_diff_pkr DECIMAL(12,2) NOT NULL,
  delivery_terms_json JSON NOT NULL,
  proposed_eta_at DATETIME NULL,
  expires_at DATETIME NOT NULL,
  quote_hash CHAR(64) NOT NULL,
  requires_buyer_consent TINYINT(1) NOT NULL DEFAULT 0,
  decision ENUM('PENDING', 'ACCEPTED', 'DECLINED', 'EXPIRED', 'APPLIED', 'SUPERSEDED') NOT NULL DEFAULT 'PENDING',
  decided_by INT NULL,
  decided_at DATETIME NULL,
  applied_at DATETIME NULL,
  idempotency_key VARCHAR(120) NOT NULL,
  decision_idempotency_key VARCHAR(120) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_delivery_amend_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_amend_stop FOREIGN KEY (stop_id) REFERENCES delivery_run_stops(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_amend_buyer FOREIGN KEY (buyer_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_amend_supplier FOREIGN KEY (supplier_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_amend_actor FOREIGN KEY (initiating_actor_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT fk_delivery_amend_decider FOREIGN KEY (decided_by) REFERENCES users(id) ON DELETE SET NULL,
  UNIQUE KEY uq_delivery_amend_code (amendment_code),
  UNIQUE KEY uq_delivery_amend_order_ver (order_id, amendment_version),
  UNIQUE KEY uq_delivery_amend_idem (order_id, idempotency_key),
  KEY idx_delivery_amend_buyer (buyer_id, decision, expires_at),
  KEY idx_delivery_amend_supplier (supplier_id, decision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
