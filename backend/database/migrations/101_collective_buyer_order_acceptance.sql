-- PR61 Part 2: each joined buyer authorizes their own payable order after qualification.
-- No payment or settlement state is written here. All new identifiers are buyer scoped.
CREATE TABLE procurement_collective_buyer_orders (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 group_id BIGINT NOT NULL,
 participant_id BIGINT NOT NULL,
 buyer_id INT NOT NULL,
 supplier_id INT NOT NULL,
 bid_version_id BIGINT NOT NULL,
 approval_id BIGINT NOT NULL,
 order_id INT NOT NULL,
 total_amount DECIMAL(14,2) NOT NULL,
 item_subtotal DECIMAL(14,2) NOT NULL,
 delivery_fee DECIMAL(12,2) NOT NULL,
 buyer_platform_fee DECIMAL(12,2) NOT NULL,
 supplier_fee DECIMAL(12,2) NOT NULL,
 supplier_commission_percent DECIMAL(5,2) NOT NULL,
 accepted_delivery_snapshot JSON NOT NULL,
 accepted_terms_snapshot JSON NOT NULL,
 idempotency_key VARCHAR(120) NOT NULL,
 payload_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_collective_buyer_order (group_id,buyer_id),
 UNIQUE KEY uq_collective_order (order_id),
 UNIQUE KEY uq_collective_order_buyer_idem (buyer_id,idempotency_key),
 KEY idx_collective_group_supplier (group_id,supplier_id),
 CONSTRAINT fk_collective_order_group FOREIGN KEY (group_id) REFERENCES procurement_collective_groups(id),
 CONSTRAINT fk_collective_order_participant FOREIGN KEY (participant_id) REFERENCES procurement_collective_participants(id),
 CONSTRAINT fk_collective_order_buyer FOREIGN KEY (buyer_id) REFERENCES users(id),
 CONSTRAINT fk_collective_order_supplier FOREIGN KEY (supplier_id) REFERENCES users(id),
 CONSTRAINT fk_collective_order_bidversion FOREIGN KEY (bid_version_id) REFERENCES procurement_collective_bid_versions(id),
 CONSTRAINT fk_collective_order_approval FOREIGN KEY (approval_id) REFERENCES procurement_collective_buyer_approvals(id),
 CONSTRAINT fk_collective_order_order FOREIGN KEY (order_id) REFERENCES orders(id),
 CONSTRAINT chk_collective_total_positive CHECK(total_amount>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE procurement_collective_order_lines (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 collective_order_id BIGINT NOT NULL,
 request_item_id BIGINT NOT NULL,
 supplier_listing_id INT NOT NULL,
 supplier_sku_id INT NOT NULL,
 product_spec_id INT NOT NULL,
 quantity DECIMAL(12,4) NOT NULL,
 purchasing_unit VARCHAR(30) NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,
 subtotal DECIMAL(14,2) NOT NULL,
 physical_snapshot JSON NOT NULL,
 UNIQUE KEY uq_collective_order_item (collective_order_id,request_item_id),
 KEY idx_collective_order_line_listing (supplier_listing_id),
 CONSTRAINT fk_collective_line_order FOREIGN KEY(collective_order_id) REFERENCES procurement_collective_buyer_orders(id),
 CONSTRAINT fk_collective_line_request FOREIGN KEY(request_item_id) REFERENCES procurement_request_items(id),
 CONSTRAINT fk_collective_line_listing FOREIGN KEY(supplier_listing_id) REFERENCES supplier_listings(id),
 CONSTRAINT fk_collective_line_sku FOREIGN KEY(supplier_sku_id) REFERENCES supplier_skus(id),
 CONSTRAINT fk_collective_line_spec FOREIGN KEY(product_spec_id) REFERENCES product_specifications(id),
 CONSTRAINT chk_collective_order_line_quantity CHECK(quantity>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
