const definitions = Object.freeze(Object.fromEntries(raw.map(([domain,name,priority]) => {
 const type = domain + '.' + name;
 return [type, Object.freeze({
   type, domain, priority,
   channels: Object.freeze(priority === 'CRITICAL' ? [CHANNELS.IN_APP,CHANNELS.EMAIL] : [CHANNELS.IN_APP]),
   dedupeScope: 'RECIPIENT_EVENT',
   transactional: true
 })];
})));
function getEventDefinition(type) {
 if (typeof type !== 'string' || !Object.prototype.hasOwnProperty.call(definitions,type)) {
   throw new Error('UNKNOWN_NOTIFICATION_EVENT');
 }
 return definitions[type];
}
function buildEventKey({type,aggregateId,aggregateVersion,transitionId}) {
 getEventDefinition(type);
 if (!aggregateId || !transitionId || !Number.isSafeInteger(aggregateVersion) || aggregateVersion < 0)
   throw new Error('INVALID_NOTIFICATION_EVENT_IDENTITY');
 // No raw user information in dedupe keys; callers must use stable opaque IDs.
 return type+':'+require('node:crypto').createHash('sha256')
   .update(JSON.stringify([String(aggregateId),aggregateVersion,String(transitionId)])).digest('hex');
}
module.exports = Object.freeze({PRIORITIES,CHANNELS,definitions,getEventDefinition,buildEventKey});
